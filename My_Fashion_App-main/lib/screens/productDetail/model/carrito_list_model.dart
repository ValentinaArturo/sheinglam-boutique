class CarritoListModel {
  final int? idCarrito;
  final Cliente? cliente;

  CarritoListModel({
    this.idCarrito,
    this.cliente,
  });

  factory CarritoListModel.fromJson(Map<String, dynamic> json) =>
      CarritoListModel(
        idCarrito: json["idCarrito"],
        cliente:
            json["cliente"] == null ? null : Cliente.fromJson(json["cliente"]),
      );
}

